
import os
from pathlib import Path

import joblib
import pyarrow.parquet as pq
import torch
from torch_geometric.data import Batch, Data
from torch_geometric.utils import to_undirected

from monroe.model.constants import BOND_TYPE_FEAT_IDX, BOND_TYPE_OTHER_CODE
from monroe.utils import printf

precomputed_graphs: dict[str, Data] = {}
embedded_mols: dict[str, torch.Tensor] = {}
_embedded_mols_version: int | None = None
_rrwp_walk_len: int | None = None


def _ensure_precomputed_graphs(parquet_path: str | Path, clear: bool = True):
    path = Path(parquet_path)
    if not path.exists():
        raise FileNotFoundError(
            f"Precomputed graphs parquet not found at {path}. "
            "Run: python -m monroe.preprocessing.build_eval_graphs --benchmark <name>"
        )
    printf(f"Loading precomputed molecule graphs from {path}")
    table = pq.read_table(path)
    global _rrwp_walk_len
    if clear:
        precomputed_graphs.clear()
        _rrwp_walk_len = None
    n_loaded = 0
    for row in table.to_pylist():
        if clear is False and row["smiles"] in precomputed_graphs:
            continue
        precomputed_graphs[row["smiles"]] = Data(
            x=torch.as_tensor(row["node_float"], dtype=torch.float32),
            node_codes=torch.as_tensor(row["node_codes"], dtype=torch.long),
            pos_in=torch.as_tensor(row["pos_in"], dtype=torch.float32),
            edge_index=torch.as_tensor(row["edge_index"], dtype=torch.long),
            edge_codes=torch.as_tensor(row["edge_codes"], dtype=torch.long),
        )
        n_loaded += 1
    printf(f"Loaded {n_loaded} precomputed molecule graphs")


def _load_or_compute_rrwp(walk_len: int, parquet_path: str | Path):
    """Load precomputed RRWP from .pt file, or compute on-the-fly as fallback.

    Attaches rrwp_nodes, rrwp_edges, and log_deg to each Data object so the
    encoder skips on-the-fly computation.

    Precomputed files are generated by:
        python scripts/preprocessing/precompute_eval_rrwp.py --walk-len 16
    """
    global _rrwp_walk_len
    # Check if any graphs still need RRWP (not just whether walk_len was set).
    # New graphs may have been added via _ensure_precomputed_graphs(clear=False)
    # after a previous _load_or_compute_rrwp call.
    needs_rrwp = any(
        not hasattr(d, "rrwp_nodes") or d.rrwp_nodes is None
        for d in precomputed_graphs.values()
    )
    if _rrwp_walk_len == walk_len and not needs_rrwp:
        return  # all graphs already have RRWP

    # Try loading precomputed .pt file
    parquet_path = Path(parquet_path)
    bench = parquet_path.stem.split("_no_sdf")[0]  # e.g. "polaris"
    rrwp_path = parquet_path.parent / f"{bench}_rrwp_{walk_len}.pt"

    if rrwp_path.exists():
        printf(f"Loading precomputed RRWP from {rrwp_path}")
        rrwp_cache = torch.load(rrwp_path, weights_only=False)
        n_hit = 0
        for smi, data in precomputed_graphs.items():
            if smi in rrwp_cache:
                entry = rrwp_cache[smi]
                data.rrwp_nodes = entry["rrwp_nodes"]
                data.rrwp_edges = entry["rrwp_edges"]
                data.log_deg = entry["log_deg"]
                n_hit += 1
        # Compute RRWP on-the-fly for molecules missing from the cache
        n_computed = 0
        for smi, data in precomputed_graphs.items():
            if hasattr(data, "rrwp_nodes") and data.rrwp_nodes is not None:
                continue
            N = data.x.size(0)
            edge_codes = data.edge_codes
            edge_index = data.edge_index
            if edge_codes.dim() < 2 or edge_index.size(1) == 0:
                continue  # encoder handles these via on-the-fly path
            is_real = edge_codes[:, BOND_TYPE_FEAT_IDX] != BOND_TYPE_OTHER_CODE
            real_ei = edge_index[:, is_real]
            ei_rw = to_undirected(real_ei, num_nodes=N)
            adj = torch.zeros(N, N, dtype=torch.float)
            adj[ei_rw[0], ei_rw[1]] = 1.0
            adj.fill_diagonal_(1.0)
            deg = adj.sum(dim=1)
            transition = adj / deg.unsqueeze(1)
            powers = []
            current = transition
            for _ in range(walk_len):
                powers.append(current)
                current = current @ transition
            probs = torch.stack(powers, dim=-1)
            data.rrwp_nodes = probs.diagonal(dim1=0, dim2=1).transpose(0, 1).contiguous()
            rows, cols = edge_index
            edge_vals = probs[rows, cols, :]
            data.rrwp_edges = (0.5 * (edge_vals + probs[cols, rows, :])).contiguous()
            data.log_deg = torch.log(deg + 1)
            n_computed += 1
        # Fill zero RRWP for edgeless molecules so all Data objects have uniform attributes
        # (required for PyG Batch.from_data_list collation in finetuning)
        n_zero = 0
        for data in precomputed_graphs.values():
            if hasattr(data, "rrwp_nodes") and data.rrwp_nodes is not None:
                continue
            N = data.x.size(0)
            E = data.edge_index.size(1)
            data.rrwp_nodes = torch.zeros(N, walk_len)
            data.rrwp_edges = torch.zeros(E, walk_len)
            data.log_deg = torch.zeros(N)
            n_zero += 1
        printf(f"Loaded RRWP for {n_hit} molecules, computed {n_computed} on-the-fly, {n_zero} zero-filled (edgeless)")
        _rrwp_walk_len = walk_len
        return

    # Fallback: compute on-the-fly
    printf(f"No precomputed RRWP at {rrwp_path}, computing on-the-fly (walk_len={walk_len})...")
    skipped = 0
    for data in precomputed_graphs.values():
        N = data.x.size(0)
        edge_index = data.edge_index
        edge_codes = data.edge_codes

        if edge_codes.dim() < 2 or edge_index.size(1) == 0:
            skipped += 1
            continue

        is_real = edge_codes[:, BOND_TYPE_FEAT_IDX] != BOND_TYPE_OTHER_CODE
        real_ei = edge_index[:, is_real]

        ei_rw = to_undirected(real_ei, num_nodes=N)
        adj = torch.zeros(N, N, dtype=torch.float)
        adj[ei_rw[0], ei_rw[1]] = 1.0
        adj.fill_diagonal_(1.0)
        deg = adj.sum(dim=1)
        transition = adj / deg.unsqueeze(1)

        powers = []
        current = transition
        for _ in range(walk_len):
            powers.append(current)
            current = current @ transition
        probs = torch.stack(powers, dim=-1)

        data.rrwp_nodes = probs.diagonal(dim1=0, dim2=1).transpose(0, 1).contiguous()
        rows, cols = edge_index
        edge_vals = probs[rows, cols, :]
        data.rrwp_edges = (0.5 * (edge_vals + probs[cols, rows, :])).contiguous()
        data.log_deg = torch.log(deg + 1)

    # Fill zero RRWP for edgeless molecules (uniform attributes for batching)
    n_zero = 0
    for data in precomputed_graphs.values():
        if hasattr(data, "rrwp_nodes") and data.rrwp_nodes is not None:
            continue
        N = data.x.size(0)
        E = data.edge_index.size(1)
        data.rrwp_nodes = torch.zeros(N, walk_len)
        data.rrwp_edges = torch.zeros(E, walk_len)
        data.log_deg = torch.zeros(N)
        n_zero += 1
    _rrwp_walk_len = walk_len
    if skipped:
        printf(f"RRWP: {n_zero} edgeless molecules zero-filled")
    printf("RRWP on-the-fly computation done")


def get_embeddings(
    smis: list[str],
    featuriser: torch.nn.Module,
    device: torch.device,
    batch_size: int = 32,
    parquet_path: str | Path = "data/polaris/polaris_no_sdf.parquet",
    bn_train_mode: bool = False,
) -> dict[str, torch.Tensor]:

    if not precomputed_graphs:
        try:
            _ensure_precomputed_graphs(parquet_path)
        except FileNotFoundError:
            printf(f"No precomputed graphs found at {parquet_path}.")

    # Load or compute RRWP once for all molecules (avoids per-forward-pass dense matmul)
    walk_len = getattr(featuriser, "walk_len", None)
    if walk_len is not None and precomputed_graphs:
        _load_or_compute_rrwp(walk_len, parquet_path)

    featuriser = featuriser.to(device)
    featuriser.eval()
    if bn_train_mode:
        for m in featuriser.modules():
            if isinstance(m, torch.nn.BatchNorm1d):
                m.train()

    result: dict[str, torch.Tensor] = {}

    # Separate molecules with and without precomputed RRWP
    # (they can't be batched together — PyG requires uniform fields)
    has_rrwp: list[tuple[str, Data]] = []
    no_rrwp: list[tuple[str, Data]] = []
    missing_smis: list[str] = []

    for smi in smis:
        graph = precomputed_graphs.get(smi)
        if graph is None:
            missing_smis.append(smi)
            continue
        if hasattr(graph, "rrwp_nodes") and graph.rrwp_nodes is not None:
            has_rrwp.append((smi, graph))
        else:
            no_rrwp.append((smi, graph))

    def _embed_batch(pairs):
        graphs = [g for _, g in pairs]
        batch = Batch.from_data_list(graphs)
        with torch.no_grad():
            batch = batch.to(device)
            embs, _ = featuriser(batch)
            embs = embs.detach().cpu()
        for (s, _), e in zip(pairs, embs):
            result[s] = e

    # Process molecules with precomputed RRWP
    for i in range(0, len(has_rrwp), batch_size):
        _embed_batch(has_rrwp[i:i + batch_size])

    # Process molecules without RRWP (encoder computes on-the-fly)
    for i in range(0, len(no_rrwp), batch_size):
        _embed_batch(no_rrwp[i:i + batch_size])

    if missing_smis:
        printf(f"Missing {len(missing_smis)} / {len(smis)} precomputed graphs:")
        for smi in missing_smis[:min(len(missing_smis), 5)]:
            printf(f"  {smi}")

    return result


def lookup_embeddings(
    smis: list[str],
    featuriser: torch.nn.Module,
    batch_size: int,
    device: torch.device,
    cache_path: str | Path | None = None,
    clear_cache: bool = False
) -> None:
    """Compute and cache embeddings for *smis* if they are not cached."""
    global _embedded_mols_version

    # Auto-clear embedding cache when a different model is used.
    # Uses a monotonic counter stored on the model to avoid stale cache
    # hits when Python recycles id() values for new objects.
    if not hasattr(featuriser, "_monroe_cache_version"):
        featuriser._monroe_cache_version = (_embedded_mols_version or 0) + 1
    model_ver = featuriser._monroe_cache_version
    if _embedded_mols_version is not None and _embedded_mols_version != model_ver:
        embedded_mols.clear()
    _embedded_mols_version = model_ver

    if clear_cache:
        global _rrwp_walk_len
        precomputed_graphs.clear()
        embedded_mols.clear()
        _rrwp_walk_len = None

    new = [s for s in smis if s not in embedded_mols]
    if new:
        embedded_mols.update(
            get_embeddings(
                smis=new,
                featuriser=featuriser,
                batch_size=batch_size,
                device=device,
            )
        )

    if cache_path is not None and len(new) > 0:
        try:
            cache_path = Path(cache_path)
            os.makedirs(cache_path.parent, exist_ok=True)
            joblib.dump(embedded_mols, cache_path)
            printf(f"Saved embedding cache ({len(embedded_mols)} entries) -> {cache_path.as_posix()}")
        except Exception as e:
            printf(f"Failed to write cache to {cache_path.as_posix()}: {e}")
